import {
  CfnOutput,
  Duration,
  Fn,
  RemovalPolicy,
  Size,
  Stack,
  Tags,
  type StackProps,
} from "aws-cdk-lib";
import * as cloudwatch from "aws-cdk-lib/aws-cloudwatch";
import * as cwActions from "aws-cdk-lib/aws-cloudwatch-actions";
import * as dlm from "aws-cdk-lib/aws-dlm";
import * as ec2 from "aws-cdk-lib/aws-ec2";
import * as ecr from "aws-cdk-lib/aws-ecr";
import * as iam from "aws-cdk-lib/aws-iam";
import * as logs from "aws-cdk-lib/aws-logs";
import * as route53 from "aws-cdk-lib/aws-route53";
import * as s3 from "aws-cdk-lib/aws-s3";
import * as secretsmanager from "aws-cdk-lib/aws-secretsmanager";
import * as sns from "aws-cdk-lib/aws-sns";
import * as ssm from "aws-cdk-lib/aws-ssm";
import type { Construct } from "constructs";
import { bundleBucketName } from "./ci-stack";
import {
  ALERT_TOPIC_NAME,
  DOC_DEPLOY,
  DOC_EMIT,
  DOC_SEED,
  ECR_API_REPO,
  ECR_WEB_REPO,
  REGION,
  SECRET_PREFIX,
  SSM_PREFIX,
  type AppStackConfig,
  type SandboxConfig,
} from "./config";

/**
 * Docker Compose plugin, delivered as a digest-pinned image so integrity is verified by
 * the registry digest (v2.40.3). Update both values together.
 */
export const COMPOSE_BIN_IMAGE =
  "docker/compose-bin@sha256:e39da8206cc48c6e2c99ce371935eef9d7eff7db600a993fd357de8b75621edf";

export const LOG_GROUP_SERVICES = [
  "api",
  "ingest",
  "web",
  "postgres",
  "nats",
  "ops",
] as const;

export interface AppStackProps extends StackProps {
  readonly sandbox: SandboxConfig;
  readonly app: AppStackConfig;
}

export class EaSbxAppStack extends Stack {
  private readonly azName: string;

  /**
   * Single, fixed AZ. Overriding this getter (documented CDK pattern) stops the Vpc construct
   * triggering an AWS availability-zones lookup, so synth needs no credentials.
   */
  override get availabilityZones(): string[] {
    return [this.azName];
  }

  constructor(scope: Construct, id: string, props: AppStackProps) {
    super(scope, id, props);
    this.azName = props.app.availabilityZone;
    const { sandbox, app } = props;

    // ---------------- Network: 1 AZ, 1 public subnet, no NAT, free S3 gateway endpoint ----------------
    const vpc = new ec2.Vpc(this, "Vpc", {
      ipAddresses: ec2.IpAddresses.cidr("10.40.0.0/16"),
      availabilityZones: [app.availabilityZone],
      natGateways: 0,
      subnetConfiguration: [
        { name: "public", subnetType: ec2.SubnetType.PUBLIC, cidrMask: 24 },
      ],
      gatewayEndpoints: {
        S3: { service: ec2.GatewayVpcEndpointAwsService.S3 },
      },
      restrictDefaultSecurityGroup: false,
    });

    // Only 443 (allowedCidrs) and 80 (ACME challenge + redirect). 22/5432/4222/8222/8080 are never opened.
    const sg = new ec2.SecurityGroup(this, "WebSg", {
      vpc,
      securityGroupName: "ea-sbx-web",
      description: "EA sandbox: 443 and 80 only",
      allowAllOutbound: true,
    });
    for (const cidr of app.allowedCidrs) {
      sg.addIngressRule(ec2.Peer.ipv4(cidr), ec2.Port.tcp(443), "HTTPS");
    }
    sg.addIngressRule(
      ec2.Peer.anyIpv4(),
      ec2.Port.tcp(80),
      "ACME HTTP-01 and HTTPS redirect",
    );

    // ---------------- Registries and bundle bucket ----------------
    const mkRepo = (
      logicalId: string,
      repositoryName: string,
    ): ecr.Repository =>
      new ecr.Repository(this, logicalId, {
        repositoryName,
        imageTagMutability: ecr.TagMutability.IMMUTABLE,
        imageScanOnPush: true,
        encryption: ecr.RepositoryEncryption.AES_256,
        emptyOnDelete: true,
        removalPolicy: RemovalPolicy.DESTROY,
        lifecycleRules: [
          { maxImageCount: 10, description: "keep the last 10 images" },
        ],
      });
    const apiRepo = mkRepo("ApiRepo", ECR_API_REPO);
    const webRepo = mkRepo("WebRepo", ECR_WEB_REPO);

    const bucket = new s3.Bucket(this, "BundleBucket", {
      bucketName: bundleBucketName(sandbox.account),
      encryption: s3.BucketEncryption.S3_MANAGED,
      blockPublicAccess: s3.BlockPublicAccess.BLOCK_ALL,
      enforceSSL: true,
      removalPolicy: RemovalPolicy.DESTROY,
      autoDeleteObjects: true,
      lifecycleRules: [
        { id: "expire-releases", expiration: Duration.days(90) },
      ],
    });

    // ---------------- Secrets: values generated by Secrets Manager, never in code ----------------
    const mkSecret = (
      logicalId: string,
      name: string,
      length: number,
    ): secretsmanager.Secret =>
      new secretsmanager.Secret(this, logicalId, {
        secretName: `${SECRET_PREFIX}/${name}`,
        description: `EA sandbox ${name} (generated)`,
        generateSecretString: {
          passwordLength: length,
          excludePunctuation: true,
        },
        removalPolicy: RemovalPolicy.DESTROY,
      });
    const pgSecret = mkSecret("PostgresSecret", "postgres", 32);
    const adminSecret = mkSecret("SeedAdminSecret", "seed-admin", 24);
    const analystSecret = mkSecret("SeedAnalystSecret", "seed-analyst", 24);

    // ---------------- Log groups (14 days) ----------------
    const logGroups: Record<string, logs.LogGroup> = {};
    for (const svc of [...LOG_GROUP_SERVICES, "ssm-sessions"] as const) {
      logGroups[svc] = new logs.LogGroup(this, `Logs-${svc}`, {
        logGroupName: `/ea/sandbox/${svc}`,
        retention: logs.RetentionDays.TWO_WEEKS,
        removalPolicy: RemovalPolicy.DESTROY,
      });
    }

    // ---------------- Instance role (section 3.6) ----------------
    const role = new iam.Role(this, "InstanceRole", {
      roleName: "ea-sbx-instance",
      assumedBy: new iam.ServicePrincipal("ec2.amazonaws.com"),
      managedPolicies: [
        iam.ManagedPolicy.fromAwsManagedPolicyName(
          "AmazonSSMManagedInstanceCore",
        ),
      ],
    });
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: "EcrAuth",
        actions: ["ecr:GetAuthorizationToken"],
        resources: ["*"],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: "EcrPull",
        actions: [
          "ecr:BatchGetImage",
          "ecr:GetDownloadUrlForLayer",
          "ecr:BatchCheckLayerAvailability",
        ],
        resources: [apiRepo.repositoryArn, webRepo.repositoryArn],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: "BundleRead",
        actions: ["s3:GetObject"],
        resources: [bucket.arnForObjects("releases/*")],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: "ReadAppSecrets",
        actions: ["secretsmanager:GetSecretValue"],
        resources: [
          pgSecret.secretArn,
          adminSecret.secretArn,
          analystSecret.secretArn,
        ],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: "ReadNonSecretParams",
        actions: ["ssm:GetParameter"],
        resources: [
          `arn:aws:ssm:${REGION}:${sandbox.account}:parameter${SSM_PREFIX}/*`,
        ],
      }),
    );
    role.addToPolicy(
      new iam.PolicyStatement({
        sid: "WriteLogs",
        actions: [
          "logs:CreateLogStream",
          "logs:PutLogEvents",
          "logs:DescribeLogStreams",
        ],
        resources: [
          `arn:aws:logs:${REGION}:${sandbox.account}:log-group:/ea/sandbox/*`,
          `arn:aws:logs:${REGION}:${sandbox.account}:log-group:/ea/sandbox/*:*`,
        ],
      }),
    );

    // ---------------- Data volume (survives instance replacement) ----------------
    const dataVolume = new ec2.Volume(this, "DataVolume", {
      volumeName: "ea-sbx-data",
      availabilityZone: app.availabilityZone,
      size: app.dataVolumeSnapshotId ? undefined : Size.gibibytes(20),
      volumeType: ec2.EbsDeviceVolumeType.GP3,
      encrypted: true,
      removalPolicy: RemovalPolicy.SNAPSHOT,
      ...(app.dataVolumeSnapshotId
        ? { snapshotId: app.dataVolumeSnapshotId }
        : {}),
    });
    Tags.of(dataVolume).add("ea:backup", "daily");

    // ---------------- Instance: IMDSv2 required, hop limit 1, no key pair, no SSH ----------------
    const volumeIdNoDash = Fn.join("", Fn.split("-", dataVolume.volumeId));
    const userData = ec2.UserData.forLinux();
    userData.addCommands(
      "set -euxo pipefail",
      // Swap (1 GiB) for memory headroom on 2 GiB.
      'if [ ! -f /swapfile ]; then fallocate -l 1G /swapfile; chmod 600 /swapfile; mkswap /swapfile; swapon /swapfile; echo "/swapfile none swap sw 0 0" >> /etc/fstab; fi',
      "dnf install -y docker",
      "systemctl enable --now docker",
      // Compose plugin from a digest-pinned image (integrity = registry digest).
      `CID=$(docker create ${COMPOSE_BIN_IMAGE} /x)`,
      "mkdir -p /usr/local/lib/docker/cli-plugins",
      'docker cp "$CID":/docker-compose /usr/local/lib/docker/cli-plugins/docker-compose',
      'docker rm "$CID"',
      "chmod 0755 /usr/local/lib/docker/cli-plugins/docker-compose",
      // Data volume: wait for attachment, format only if blank, mount by UUID.
      `DEV=/dev/disk/by-id/nvme-Amazon_Elastic_Block_Store_${volumeIdNoDash}`,
      'for i in $(seq 1 90); do [ -e "$DEV" ] && break; sleep 5; done',
      '[ -e "$DEV" ] || { echo "data volume did not attach" >&2; exit 1; }',
      'if ! blkid "$DEV" >/dev/null 2>&1; then mkfs.xfs "$DEV"; fi',
      "mkdir -p /data",
      'UUID=$(blkid -s UUID -o value "$DEV")',
      'grep -q "$UUID" /etc/fstab || echo "UUID=$UUID /data xfs defaults,nofail 0 2" >> /etc/fstab',
      "mount -a",
      "mkdir -p /data/pg /data/nats /data/caddy /data/backups /opt/ea/releases",
      // caddy and nats containers run as uid 10001 (non-root); postgres chowns its own dir.
      "chown 10001:10001 /data/caddy /data/nats",
      "chmod 0700 /data/backups",
    );

    const instance = new ec2.Instance(this, "Instance", {
      instanceName: "ea-sbx",
      vpc,
      vpcSubnets: { subnetType: ec2.SubnetType.PUBLIC },
      instanceType: new ec2.InstanceType(app.instanceType),
      machineImage: ec2.MachineImage.genericLinux({ [REGION]: app.amiId }),
      securityGroup: sg,
      role,
      userData,
      userDataCausesReplacement: false,
      blockDevices: [
        {
          deviceName: "/dev/xvda",
          volume: ec2.BlockDeviceVolume.ebs(20, {
            volumeType: ec2.EbsDeviceVolumeType.GP3,
            encrypted: true,
            deleteOnTermination: true,
          }),
        },
      ],
    });
    const cfnInstance = instance.node.defaultChild as ec2.CfnInstance;
    cfnInstance.addPropertyOverride("MetadataOptions", {
      HttpTokens: "required",
      HttpPutResponseHopLimit: 1,
      HttpEndpoint: "enabled",
    });
    new ec2.CfnVolumeAttachment(this, "DataAttachment", {
      device: "/dev/sdf",
      instanceId: instance.instanceId,
      volumeId: dataVolume.volumeId,
    });

    // ---------------- Elastic IP and site host (sslip.io unless siteHost is supplied) ----------------
    const eip = new ec2.CfnEIP(this, "Eip", { domain: "vpc" });
    new ec2.CfnEIPAssociation(this, "EipAssociation", {
      instanceId: instance.instanceId,
      allocationId: eip.attrAllocationId,
    });
    const siteHost =
      app.siteHost ??
      Fn.join("", [Fn.join("-", Fn.split(".", eip.ref)), ".sslip.io"]);

    // ---------------- Non-secret parameters (data-classification is hard-coded) ----------------
    const param = (
      logicalId: string,
      name: string,
      value: string,
    ): ssm.StringParameter =>
      new ssm.StringParameter(this, logicalId, {
        parameterName: `${SSM_PREFIX}/${name}`,
        stringValue: value,
        tier: ssm.ParameterTier.STANDARD,
      });
    param("ParamSiteHost", "site-host", siteHost);
    param("ParamDataClassification", "data-classification", "synthetic");
    param(
      "ParamEcrRegistry",
      "ecr-registry",
      `${sandbox.account}.dkr.ecr.${REGION}.amazonaws.com`,
    );
    param("ParamBundleBucket", "bundle-bucket", bucket.bucketName);
    param("ParamAcmeCa", "acme-ca", app.acmeCa);

    // ---------------- SSM documents: the only thing the pipeline can run on the host ----------------
    const mkDoc = (
      logicalId: string,
      name: string,
      description: string,
      scriptArgs: string,
    ): ssm.CfnDocument =>
      new ssm.CfnDocument(this, logicalId, {
        name,
        documentType: "Command",
        documentFormat: "JSON",
        updateMethod: "NewVersion",
        content: {
          schemaVersion: "2.2",
          description,
          parameters: {
            imageTag: {
              type: "String",
              description:
                "Full 40-character lowercase git commit SHA (the immutable image tag).",
              allowedPattern: "^[0-9a-f]{40}$",
            },
          },
          mainSteps: [
            {
              action: "aws:runShellScript",
              name: "run",
              inputs: {
                timeoutSeconds: "900",
                runCommand: [
                  "set -euo pipefail",
                  "export AWS_DEFAULT_REGION=" + REGION,
                  "install -d -m 0755 /opt/ea/releases/{{imageTag}}",
                  `aws s3 cp --only-show-errors --recursive s3://${bucket.bucketName}/releases/{{imageTag}}/ /opt/ea/releases/{{imageTag}}/`,
                  `bash /opt/ea/releases/{{imageTag}}/deploy.sh ${scriptArgs}{{imageTag}}`,
                ],
              },
            },
          ],
        },
      });
    mkDoc(
      "DocDeploy",
      DOC_DEPLOY,
      "Deploy a release bundle (migrate, then recreate api/ingest/web)",
      "",
    );
    mkDoc(
      "DocSeed",
      DOC_SEED,
      "Run the guarded synthetic seed for a release",
      "--seed ",
    );
    mkDoc(
      "DocEmit",
      DOC_EMIT,
      "Emit synthetic demo events with the producer client",
      "--emit-demo ",
    );

    // ---------------- Alarms -> SNS topic owned by EaSbxCiStack (imported by ARN) ----------------
    const topic = sns.Topic.fromTopicArn(
      this,
      "AlertTopic",
      `arn:aws:sns:${REGION}:${sandbox.account}:${ALERT_TOPIC_NAME}`,
    );
    const snsAction = new cwActions.SnsAction(topic);
    const statusMetric = (metricName: string): cloudwatch.Metric =>
      new cloudwatch.Metric({
        namespace: "AWS/EC2",
        metricName,
        dimensionsMap: { InstanceId: instance.instanceId },
        statistic: "Maximum",
        period: Duration.minutes(1),
      });
    const sysAlarm = new cloudwatch.Alarm(this, "AlarmSystemCheck", {
      alarmName: "ea-sbx-status-check-system",
      metric: statusMetric("StatusCheckFailed_System"),
      threshold: 1,
      evaluationPeriods: 2,
      comparisonOperator:
        cloudwatch.ComparisonOperator.GREATER_THAN_OR_EQUAL_TO_THRESHOLD,
      treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
    });
    sysAlarm.addAlarmAction(
      new cwActions.Ec2Action(cwActions.Ec2InstanceAction.RECOVER),
      snsAction,
    );
    const instAlarm = new cloudwatch.Alarm(this, "AlarmInstanceCheck", {
      alarmName: "ea-sbx-status-check-instance",
      metric: statusMetric("StatusCheckFailed_Instance"),
      threshold: 1,
      evaluationPeriods: 3,
      comparisonOperator:
        cloudwatch.ComparisonOperator.GREATER_THAN_OR_EQUAL_TO_THRESHOLD,
      treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
    });
    instAlarm.addAlarmAction(snsAction);

    const healthCheck = new route53.CfnHealthCheck(this, "ReadyHealthCheck", {
      healthCheckConfig: {
        type: "HTTPS_STR_MATCH",
        fullyQualifiedDomainName: siteHost,
        port: 443,
        resourcePath: "/health/ready",
        searchString: '"status":"ok"',
        requestInterval: 30,
        failureThreshold: 3,
        enableSni: true,
      },
      healthCheckTags: [{ key: "Name", value: "ea-sbx-ready" }],
    });
    const availability = new cloudwatch.Alarm(this, "AlarmAvailability", {
      alarmName: "ea-sbx-app-availability",
      metric: new cloudwatch.Metric({
        namespace: "AWS/Route53",
        metricName: "HealthCheckStatus",
        dimensionsMap: { HealthCheckId: healthCheck.attrHealthCheckId },
        statistic: "Minimum",
        period: Duration.minutes(1),
      }),
      threshold: 1,
      evaluationPeriods: 2,
      comparisonOperator: cloudwatch.ComparisonOperator.LESS_THAN_THRESHOLD,
      treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
    });
    availability.addAlarmAction(snsAction);

    const logAlarm = (
      id: string,
      group: logs.LogGroup,
      pattern: string,
      metricName: string,
      alarmName: string,
    ): void => {
      const filter = new logs.MetricFilter(this, `${id}Filter`, {
        logGroup: group,
        filterPattern: logs.FilterPattern.literal(pattern),
        metricNamespace: "EaSbx",
        metricName,
        metricValue: "1",
        defaultValue: 0,
      });
      new cloudwatch.Alarm(this, `${id}Alarm`, {
        alarmName,
        metric: filter.metric({
          statistic: "Sum",
          period: Duration.minutes(5),
        }),
        threshold: 0,
        evaluationPeriods: 1,
        comparisonOperator:
          cloudwatch.ComparisonOperator.GREATER_THAN_THRESHOLD,
        treatMissingData: cloudwatch.TreatMissingData.NOT_BREACHING,
      }).addAlarmAction(snsAction);
    };
    const ingestLogs = logGroups["ingest"];
    const pgLogs = logGroups["postgres"];
    if (!ingestLogs || !pgLogs) throw new Error("log groups missing");
    logAlarm(
      "IngestWorkerFailed",
      ingestLogs,
      '"Ingestion worker failed"',
      "IngestWorkerFailed",
      "ea-sbx-ingest-worker-failed",
    );
    logAlarm(
      "PostgresDiskFull",
      pgLogs,
      '"No space left on device"',
      "PostgresDiskFull",
      "ea-sbx-postgres-disk-full",
    );

    // ---------------- Daily snapshots of volumes tagged ea:backup=daily (03:00 UTC, keep 7) ----------------
    const dlmRole = new iam.Role(this, "DlmRole", {
      assumedBy: new iam.ServicePrincipal("dlm.amazonaws.com"),
      managedPolicies: [
        iam.ManagedPolicy.fromAwsManagedPolicyName(
          "service-role/AWSDataLifecycleManagerServiceRole",
        ),
      ],
    });
    new dlm.CfnLifecyclePolicy(this, "DailySnapshots", {
      description: "EA sandbox daily data-volume snapshot",
      state: "ENABLED",
      executionRoleArn: dlmRole.roleArn,
      policyDetails: {
        resourceTypes: ["VOLUME"],
        targetTags: [{ key: "ea:backup", value: "daily" }],
        schedules: [
          {
            name: "daily",
            copyTags: true,
            createRule: {
              interval: 24,
              intervalUnit: "HOURS",
              times: ["03:00"],
            },
            retainRule: { count: 7 },
          },
        ],
      },
    });

    // ---------------- Outputs (non-secret; map to GitHub environment variables) ----------------
    new CfnOutput(this, "SiteHost", {
      value: siteHost,
      description: "GitHub environment variable SITE_HOST",
    });
    new CfnOutput(this, "ElasticIp", { value: eip.ref });
    new CfnOutput(this, "InstanceId", { value: instance.instanceId });
    new CfnOutput(this, "DataVolumeId", { value: dataVolume.volumeId });
    new CfnOutput(this, "EcrApiUri", { value: apiRepo.repositoryUri });
    new CfnOutput(this, "EcrWebUri", { value: webRepo.repositoryUri });
    new CfnOutput(this, "BundleBucketName", {
      value: bucket.bucketName,
      description: "GitHub environment variable BUNDLE_BUCKET",
    });
  }
}
